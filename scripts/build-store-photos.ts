/**
 * Builds optimised store photos for the homepage hero and gallery.
 *
 *   1. Put JPEG/PNG/WebP photos in  assets/store-photos/
 *      - files are shown in name order (prefix with 01-, 02-… to control it)
 *      - "storefront.*" is used for the "Visit us" card, not the slideshow
 *      - files whose name contains "counter" appear only in the gallery strip
 *   2. Run  npm run photos:build
 *
 * Output: public/store/<name>.webp (1920 px) and <name>-thumb.webp (560 px), plus
 * src/components/storefront/store-photos.ts with static imports (so next/image
 * gets dimensions and an automatic blur placeholder).
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SRC = path.resolve("assets/store-photos");
const OUT = path.resolve("public/store");
const MANIFEST = path.resolve("src/components/storefront/store-photos.ts");

/** Captions for the current photos; new files fall back to a title from their name. */
const CAPTIONS: Record<string, string> = {
  "01-stationery-craft": "Stationery & craft supplies",
  "02-notebooks-paper": "Notebooks & paper",
  "03-steel-kitchenware": "Steel kitchenware",
  "04-kitchen-appliances": "Kitchen appliances & homeware",
  "05-school-essentials": "School essentials",
  "06-bags-toys-home": "Bags, toys & home goods",
  "07-steel-vessels": "Steel vessels & utensils",
  "08-kitchen-dining": "Kitchen & dining",
  "09-store-counter": "Inside our Palani store",
  storefront: "Aarudhra Smart Store, New Ammumall Complex, Palani",
};

const titleFromName = (base: string) =>
  base
    .replace(/^\d+[-_\s]*/, "")
    .replace(/[-_]+/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());

async function main() {
  if (!fs.existsSync(SRC)) throw new Error(`Missing folder ${SRC}`);
  fs.mkdirSync(OUT, { recursive: true });
  const files = fs
    .readdirSync(SRC, { withFileTypes: true })
    .filter((d) => d.isFile() && /\.(jpe?g|png|webp)$/i.test(d.name))
    .map((d) => d.name)
    .sort();
  if (!files.length) throw new Error("No photos found in assets/store-photos/");

  // Remove stale outputs so deleted photos don't linger.
  for (const f of fs.readdirSync(OUT)) if (f.endsWith(".webp")) fs.unlinkSync(path.join(OUT, f));

  type Entry = { base: string; ident: string; caption: string; thumbW: number; thumbH: number; role: "slide" | "gallery" | "storefront" };
  const entries: Entry[] = [];
  let total = 0;

  for (const file of files) {
    const base = path.parse(file).name.toLowerCase().replace(/[^a-z0-9-]+/g, "-");
    const input = sharp(path.join(SRC, file)).rotate();
    const full = await input.clone().resize({ width: 1920, withoutEnlargement: true }).webp({ quality: 70, effort: 6 }).toBuffer();
    const thumb = await input.clone().resize({ width: 560, height: 420, fit: "cover" }).webp({ quality: 70, effort: 6 }).toBuffer({ resolveWithObject: true });
    fs.writeFileSync(path.join(OUT, `${base}.webp`), full);
    fs.writeFileSync(path.join(OUT, `${base}-thumb.webp`), thumb.data);
    total += full.length + thumb.data.length;
    const role = base === "storefront" ? "storefront" : base.includes("counter") ? "gallery" : "slide";
    entries.push({
      base,
      ident: `p_${base.replace(/-/g, "_")}`,
      caption: CAPTIONS[base] ?? titleFromName(base),
      thumbW: thumb.info.width,
      thumbH: thumb.info.height,
      role,
    });
    console.log(`✔ ${file} → ${base}.webp (${Math.round(full.length / 1024)} KB) + thumb (${Math.round(thumb.data.length / 1024)} KB)`);
  }

  const imports = entries.map((e) => `import ${e.ident} from "../../../public/store/${e.base}.webp";`).join("\n");
  const item = (e: Entry) =>
    `  { id: "${e.base}", src: ${e.ident}, thumb: { src: "/store/${e.base}-thumb.webp", width: ${e.thumbW}, height: ${e.thumbH} }, caption: ${JSON.stringify(e.caption)} },`;
  const storefront = entries.find((e) => e.role === "storefront");

  fs.writeFileSync(
    MANIFEST,
    `// GENERATED by scripts/build-store-photos.ts — do not edit by hand.
// Add photos to assets/store-photos/ and run \`npm run photos:build\`.
import type { StaticImageData } from "next/image";
${imports}

export type StorePhoto = {
  id: string;
  src: StaticImageData;
  thumb: { src: string; width: number; height: number };
  caption: string;
};

/** Hero slideshow, in order. */
export const HERO_PHOTOS: StorePhoto[] = [
${entries.filter((e) => e.role === "slide").map(item).join("\n")}
];

/** "Inside our store" gallery strip (all store photos). */
export const GALLERY_PHOTOS: StorePhoto[] = [
${entries.filter((e) => e.role !== "storefront").map(item).join("\n")}
];

/** Shop front / signboard for the "Visit us" card. */
export const STOREFRONT_PHOTO: StorePhoto | null = ${storefront ? item(storefront).trim().replace(/,$/, "") : "null"};
`,
  );
  console.log(`\n✔ ${entries.length} photos, ${Math.round(total / 1024)} KB total → public/store/ and ${path.relative(process.cwd(), MANIFEST)}`);
}

main().catch((err) => {
  console.error(`✖ ${err instanceof Error ? err.message : err}`);
  process.exitCode = 1;
});
